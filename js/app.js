// Placeholder icons only (no official game art — see notes elsewhere on why).
const ELEMENT_ICON = { Pyro: '🔥', Hydro: '💧', Electro: '⚡', Cryo: '❄️', Anemo: '🌪️', Geo: '🪨', Dendro: '🌿' };
const WEAPON_TYPE_ICON = { Sword: '🗡️', Claymore: '⚔️', Polearm: '🔱', Bow: '🏹', Catalyst: '📖' };
const SLOT_ICON = { flower: '🌸', plume: '🪶', sands: '⏳', goblet: '🏆', circlet: '👑' };

function initials(name) {
  const words = String(name).replace(/\(.*?\)/g, '').trim().split(/\s+/).filter(Boolean);
  if (words.length === 0) return '?';
  if (words.length === 1) return words[0].slice(0, 2).toUpperCase();
  return (words[0][0] + words[words.length - 1][0]).toUpperCase();
}

// Real character face art from EnkaNetwork's public UI asset CDN (enka.network/ui/*),
// which they host specifically for third-party community tools. Falls back to the
// colored-initials placeholder if there's no mapped icon or the image fails to load.
function avatarHtml(character, sizeClass) {
  const cls = 'char-avatar avatar-' + character.element.toLowerCase() + (sizeClass ? ' ' + sizeClass : '');
  const fallbackSpan = `<span class="${cls}">${initials(character.name)}</span>`;
  const key = GENSHIN_DATA.characterIcons[character.id];
  if (!key) return fallbackSpan;
  const url = `https://enka.network/ui/UI_AvatarIcon_${key}.png`;
  const onerror = `this.outerHTML='${fallbackSpan.replace(/'/g, "&#39;").replace(/"/g, '&quot;')}'`;
  return `<img src="${url}" alt="${escapeHtml(character.name)}" class="${cls} char-avatar-img" onerror="${onerror}">`;
}

// Real weapon icon from the same CDN, falling back to the emoji weapon-type glyph.
function weaponIconHtml(weaponInstance) {
  const emoji = WEAPON_TYPE_ICON[weaponInstance.type] || '';
  const def = weaponInstance.weaponId ? GENSHIN_DATA.weapons.find((w) => w.id === weaponInstance.weaponId) : null;
  if (!def || !def.icon) return `<span class="icon-tag">${emoji}</span>`;
  const url = `https://enka.network/ui/${def.icon}.png`;
  const onerror = `this.outerHTML='<span class=&quot;icon-tag&quot;>${emoji}</span>'`;
  return `<img src="${url}" alt="" class="weapon-icon" onerror="${onerror}">`;
}

function isPreferredWeapon(characterId, weaponId) {
  const list = GENSHIN_DATA.preferredWeapons && GENSHIN_DATA.preferredWeapons[characterId];
  return !!(list && weaponId && list.includes(weaponId));
}

// --- Third-party roster import (e.g. a character list generated by another AI chat) ---
const NAME_ALIASES = { itto: 'aratakiitto', heizou: 'shikanoinheizou' };

function normalizeName(str) {
  return String(str).toLowerCase().replace(/\(.*?\)/g, '').replace(/[^a-z0-9]/g, '').trim();
}

function findCharacterByName(name) {
  let norm = normalizeName(name);
  if (NAME_ALIASES[norm]) norm = NAME_ALIASES[norm];
  return Store.allCharacters().find((c) => normalizeName(c.name) === norm) || null;
}

function looksLikeGeminiRoster(parsed) {
  return !!(parsed && typeof parsed === 'object' && parsed.characters &&
    (Array.isArray(parsed.characters.five_star) || Array.isArray(parsed.characters.four_star)));
}

function importGeminiRoster(parsed) {
  const entries = [];
  const skipped = [];
  const specialUnits = (parsed.account_overview && parsed.account_overview.special_units) || [];
  specialUnits.forEach((u) => {
    if (u.source) { skipped.push(`${u.name} (event/collab unit from ${u.source}, not a standard roster addition)`); return; }
    entries.push({ name: u.name, constellation: null, level: u.level != null ? u.level : null });
  });
  const fiveStar = parsed.characters.five_star || [];
  const fourStar = parsed.characters.four_star || [];
  fiveStar.concat(fourStar).forEach((c) => {
    entries.push({ name: c.name, constellation: c.constellation || null, level: c.level != null ? c.level : null });
  });

  const matched = [];
  const unmatched = [];
  entries.forEach((e) => {
    const character = findCharacterByName(e.name);
    if (character) {
      Store.setOwned(character.id, true);
      Store.setRosterMeta(character.id, { constellation: e.constellation, level: e.level });
      matched.push(character.name);
    } else {
      unmatched.push(e.name);
    }
  });
  return { matched, unmatched, skipped };
}

// --- Third-party weapon inventory import ---
function looksLikeGeminiWeaponInventory(parsed) {
  return !!(parsed && typeof parsed === 'object' && parsed.weapons && !Array.isArray(parsed.weapons) &&
    (Array.isArray(parsed.weapons.five_star) || (parsed.weapons.four_star_and_three_star && typeof parsed.weapons.four_star_and_three_star === 'object')));
}

function parseRefinement(r) {
  const m = String(r).match(/\d+/);
  return m ? Number(m[0]) : 1;
}

function parseLevel(l) {
  if (l == null) return null;
  const m = String(l).match(/\d+/);
  return m ? Number(m[0]) : null;
}

function findWeaponByName(name) {
  const norm = normalizeName(name);
  return GENSHIN_DATA.weapons.find((w) => normalizeName(w.name) === norm) || null;
}

function importGeminiWeapons(parsed) {
  const rawEntries = (parsed.weapons.five_star || []).slice();
  const grouped = parsed.weapons.four_star_and_three_star || {};
  Object.keys(grouped).forEach((cat) => rawEntries.push(...(grouped[cat] || [])));

  const matched = [];
  const unmatched = [];
  rawEntries.forEach((w) => {
    const def = findWeaponByName(w.name);
    if (!def) { unmatched.push(w.name); return; }
    const refinement = parseRefinement(w.refinement);
    const assignedName = w.assigned_to;
    let assignedTo = null;
    if (assignedName && typeof assignedName === 'string' && !/unassigned/i.test(assignedName) && !assignedName.includes('/')) {
      const char = findCharacterByName(assignedName);
      if (char) assignedTo = char.id;
    }
    const copies = w.copies || 1;
    for (let i = 0; i < copies; i++) {
      const weapon = Store.addWeapon({
        weaponId: def.id,
        name: def.name,
        type: def.type,
        refinement,
        baseAtk: def.baseAtk,
        subStat: def.subStat,
        subStatValue: def.subStatValue,
      });
      if (i === 0 && assignedTo) { weapon.assignedTo = assignedTo; Store.save(); }
    }
    matched.push(def.name);
  });
  return { matched, unmatched };
}

document.addEventListener('DOMContentLoaded', init);

function init() {
  Store.load();
  if (!Store.testPersistence()) {
    const banner = document.createElement('div');
    banner.className = 'persistence-warning';
    banner.textContent = "⚠ This browser/window isn't saving data between reloads (likely private/incognito mode, or a \"clear data on close\" setting). Anything you enter here will be lost when you close this tab — use Export before closing, or reopen this page in a normal browser window.";
    document.body.insertBefore(banner, document.body.firstChild);
  }
  document.querySelectorAll('.tab-btn').forEach((btn) => {
    btn.addEventListener('click', () => switchTab(btn.dataset.tab));
  });
  document.getElementById('export-btn').addEventListener('click', doExport);
  document.getElementById('import-input').addEventListener('change', doImport);
  document.getElementById('reset-btn').addEventListener('click', doReset);
  initCloudSyncUi();
  switchTab('characters');
}

function initCloudSyncUi() {
  const panel = document.getElementById('cloud-sync-panel');
  const statusEl = document.getElementById('cloud-sync-status');
  const setStatus = (msg, isError) => {
    statusEl.textContent = msg;
    statusEl.style.color = isError ? 'var(--danger)' : '';
  };

  document.getElementById('cloud-sync-btn').addEventListener('click', () => {
    panel.hidden = !panel.hidden;
    if (!panel.hidden) setStatus(CloudSync.getPat() ? 'Token saved on this device.' : 'No token saved on this device yet.');
  });

  document.getElementById('cloud-pat-save-btn').addEventListener('click', () => {
    const input = document.getElementById('cloud-pat-input');
    const pat = input.value.trim();
    if (!pat) { setStatus('Enter a token first.', true); return; }
    CloudSync.setPat(pat);
    input.value = '';
    setStatus('Token saved on this device.');
  });

  document.getElementById('cloud-push-btn').addEventListener('click', async () => {
    setStatus('Pushing…');
    try {
      await CloudSync.push();
      setStatus('Pushed. This device\'s data is now the cloud copy — pull it on your other device(s).');
    } catch (err) {
      setStatus(err.message, true);
    }
  });

  document.getElementById('cloud-pull-btn').addEventListener('click', async () => {
    if (!confirm('This replaces everything currently saved on this device with the cloud copy. Continue?')) return;
    setStatus('Pulling…');
    try {
      const content = await CloudSync.pull();
      Store.importJson(content);
      lastWeaponAssignmentResult = null;
      renderTab();
      setStatus('Pulled cloud data into this device.');
    } catch (err) {
      setStatus(err.message, true);
    }
  });
}

function switchTab(tab) {
  currentTab = tab;
  document.querySelectorAll('.tab-btn').forEach((btn) => btn.classList.toggle('active', btn.dataset.tab === tab));
  renderTab();
}

function renderTab() {
  const app = document.getElementById('app');
  if (currentTab === 'characters') renderCharactersTab(app);
  else if (currentTab === 'weapons') renderWeaponsTab(app);
  else if (currentTab === 'artifacts') renderArtifactsTab(app);
  else if (currentTab === 'weaponOptimizer') renderWeaponOptimizerTab(app);
  else if (currentTab === 'artifactOptimizer') renderArtifactOptimizerTab(app);
}

function escapeHtml(str) {
  return String(str).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function doExport() {
  const blob = new Blob([Store.exportJson()], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'genshin-optimizer-data.json';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function doImport(e) {
  const file = e.target.files[0];
  if (!file) return;
  const reader = new FileReader();
  reader.onload = () => {
    let parsed;
    try {
      parsed = JSON.parse(reader.result);
    } catch (err) {
      alert('Import failed: file is not valid JSON.');
      return;
    }
    try {
      if (looksLikeGeminiRoster(parsed)) {
        const { matched, unmatched, skipped } = importGeminiRoster(parsed);
        lastWeaponAssignmentResult = null;
        switchTab('characters');
        const total = matched.length + unmatched.length + skipped.length;
        let msg = `Found ${total} entries in the file. Imported ${matched.length} as owned characters.`;
        if (unmatched.length) msg += `\n\nCouldn't match ${unmatched.length} (not in my built-in list): ${unmatched.join(', ')}. Add these via "Add a custom character" if you want them tracked.`;
        if (skipped.length) msg += `\n\nSkipped ${skipped.length}: ${skipped.join(', ')}.`;
        alert(msg);
      } else if (looksLikeGeminiWeaponInventory(parsed)) {
        const { matched, unmatched } = importGeminiWeapons(parsed);
        lastWeaponAssignmentResult = null;
        switchTab('weapons');
        let msg = `Imported ${matched.length} weapon(s) into your inventory.`;
        if (unmatched.length) msg += `\n\nCouldn't match ${unmatched.length} (not in my built-in weapon list): ${unmatched.join(', ')}. Add these manually via "Custom weapon" in the Weapons tab if you want them tracked.`;
        alert(msg);
      } else if (parsed && (Array.isArray(parsed.weapons) || Array.isArray(parsed.artifacts) || Array.isArray(parsed.customCharacters) || (parsed.roster && typeof parsed.roster === 'object' && !Array.isArray(parsed.roster)))) {
        Store.importJson(reader.result);
        const s = Store.state;
        const ownedCount = Object.values(s.roster).filter((r) => r.owned).length;
        lastWeaponAssignmentResult = null;
        switchTab('characters');
        alert(`Data imported: ${ownedCount} owned character(s), ${s.weapons.length} weapon(s), ${s.artifacts.length} artifact(s).`);
      } else {
        alert("This JSON doesn't match a format I recognize (neither this app's export, nor a roster/weapon file I know how to read).");
      }
    } catch (err) {
      console.error('Import failed:', err);
      alert('Import failed: ' + err.message);
    }
  };
  reader.readAsText(file);
  e.target.value = '';
}

function doReset() {
  if (confirm('This clears all your saved characters, weapons, and artifacts. Continue?')) {
    Store.reset();
    lastWeaponAssignmentResult = null;
    renderTab();
  }
}

