function renderWeaponsTab(app) {
  app.innerHTML = `
    <section class="panel">
      <h2>My Weapons</h2>
      <p class="hint">Pick a weapon to prefill its reference stats (Level 90), then adjust if your copy differs.</p>
      <form id="add-weapon-form" class="inline-form">
        <label>Type<select id="wpn-type">${GENSHIN_DATA.weaponTypes.map((t) => `<option value="${t}">${t}</option>`).join('')}</select></label>
        <label>Weapon<select id="wpn-select"></select></label>
        <label id="wpn-custom-name-wrap" style="display:none;">Custom name<input type="text" id="wpn-custom-name" placeholder="Weapon name"></label>
        <label>Refine<select id="wpn-refine">${[1, 2, 3, 4, 5].map((r) => `<option value="${r}">R${r}</option>`).join('')}</select></label>
        <label>Base ATK<input type="number" id="wpn-atk" step="0.1" required></label>
        <label>Substat
          <select id="wpn-substat">${GENSHIN_DATA.substatKeys.concat(['elementalDmg', 'physicalDmg']).map((s) => `<option value="${s}">${GENSHIN_DATA.statLabels[s] || s}</option>`).join('')}</select>
        </label>
        <label>Substat value<input type="number" id="wpn-substat-value" step="0.1"></label>
        <button type="submit">Add weapon</button>
      </form>
      <div id="weapon-filter-tabs" class="subtabs"></div>
      <div id="weapon-list"></div>
    </section>
  `;

  const typeSel = document.getElementById('wpn-type');
  const wpnSel = document.getElementById('wpn-select');
  const customNameWrap = document.getElementById('wpn-custom-name-wrap');
  const customName = document.getElementById('wpn-custom-name');
  const atkInput = document.getElementById('wpn-atk');
  const substatSel = document.getElementById('wpn-substat');
  const substatValInput = document.getElementById('wpn-substat-value');

  function populateWeaponOptions() {
    const type = typeSel.value;
    const list = GENSHIN_DATA.weapons.filter((w) => w.type === type);
    wpnSel.innerHTML = list.map((w) => `<option value="${w.id}">${escapeHtml(w.name)} (${'★'.repeat(w.rarity)})</option>`).join('')
      + `<option value="__custom__">— Custom weapon —</option>`;
    onWeaponPick();
  }

  function onWeaponPick() {
    const val = wpnSel.value;
    if (val === '__custom__') {
      customNameWrap.style.display = '';
      substatSel.disabled = false;
      atkInput.value = '';
      substatValInput.value = '';
    } else {
      customNameWrap.style.display = 'none';
      const w = GENSHIN_DATA.weapons.find((x) => x.id === val);
      if (w) {
        atkInput.value = w.baseAtk;
        substatSel.value = w.subStat;
        substatValInput.value = w.subStatValue;
      }
      substatSel.disabled = true;
    }
  }

  typeSel.addEventListener('change', populateWeaponOptions);
  wpnSel.addEventListener('change', onWeaponPick);
  populateWeaponOptions();

  document.getElementById('add-weapon-form').addEventListener('submit', (e) => {
    e.preventDefault();
    const type = typeSel.value;
    const val = wpnSel.value;
    const name = val === '__custom__'
      ? (customName.value.trim() || 'Custom Weapon')
      : ((GENSHIN_DATA.weapons.find((w) => w.id === val) || {}).name || 'Weapon');
    const weapon = {
      weaponId: val === '__custom__' ? null : val,
      name,
      type,
      refinement: Number(document.getElementById('wpn-refine').value),
      baseAtk: Number(atkInput.value) || 0,
      subStat: substatSel.value,
      subStatValue: Number(substatValInput.value) || 0,
    };
    Store.addWeapon(weapon);
    renderWeaponsTab(app);
  });

  renderWeaponFilterTabs();
  renderWeaponList();
}

function renderWeaponFilterTabs() {
  const container = document.getElementById('weapon-filter-tabs');
  if (!container) return;
  const present = GENSHIN_DATA.weaponTypes.filter((t) => Store.state.weapons.some((w) => w.type === t));
  const tabs = ['All', ...present];
  container.innerHTML = tabs.map((t) =>
    `<button class="subtab-btn ${weaponTypeFilter === t ? 'active' : ''}" data-type="${t}">${t === 'All' ? 'All' : (WEAPON_TYPE_ICON[t] || '') + ' ' + t}</button>`
  ).join('');
  container.querySelectorAll('.subtab-btn').forEach((btn) => {
    btn.addEventListener('click', () => {
      weaponTypeFilter = btn.dataset.type;
      renderWeaponFilterTabs();
      renderWeaponList();
    });
  });
}

function weaponRarity(w) {
  const def = w.weaponId ? GENSHIN_DATA.weapons.find((x) => x.id === w.weaponId) : null;
  return def ? def.rarity : 0;
}

function renderWeaponRow(w) {
  const assignedChar = w.assignedTo ? Store.getCharacter(w.assignedTo) : null;
  const rarity = weaponRarity(w);
  const stars = rarity ? '★'.repeat(rarity) : '';
  return `<tr>
    <td>${weaponIconHtml(w)} ${escapeHtml(w.name)}${stars ? ` <span class="rarity-stars rarity-${rarity}">${stars}</span>` : ''}</td>
    <td>${WEAPON_TYPE_ICON[w.type] || ''} ${w.type}</td>
    <td>R${w.refinement}</td>
    <td>${w.baseAtk}</td>
    <td>${GENSHIN_DATA.statLabels[w.subStat] || w.subStat}: ${w.subStatValue}</td>
    <td>${assignedChar ? `${avatarHtml(assignedChar, 'avatar-sm')} ${escapeHtml(assignedChar.name)}` : '—'}</td>
    <td><button class="danger-btn" data-id="${w.instanceId}">Remove</button></td>
  </tr>`;
}

function renderWeaponList() {
  const container = document.getElementById('weapon-list');
  if (!container) return;
  const weapons = Store.state.weapons;
  if (weapons.length === 0) { container.innerHTML = '<p class="hint">No weapons added yet.</p>'; return; }

  const byRarityThenName = (a, b) => (weaponRarity(b) - weaponRarity(a)) || a.name.localeCompare(b.name);
  const types = weaponTypeFilter === 'All' ? GENSHIN_DATA.weaponTypes : [weaponTypeFilter];
  const groups = types
    .map((type) => ({ type, items: weapons.filter((w) => w.type === type).sort(byRarityThenName) }))
    .filter((g) => g.items.length);

  if (groups.length === 0) { container.innerHTML = '<p class="hint">No weapons of this type yet.</p>'; return; }

  container.innerHTML = groups.map((g) => `
    ${weaponTypeFilter === 'All' ? `<div class="group-header">${WEAPON_TYPE_ICON[g.type] || ''} ${g.type}</div>` : ''}
    <table class="data-table">
      <thead><tr><th>Weapon</th><th>Type</th><th>Refine</th><th>ATK</th><th>Substat</th><th>Assigned to</th><th></th></tr></thead>
      <tbody>${g.items.map(renderWeaponRow).join('')}</tbody>
    </table>
  `).join('');

  container.querySelectorAll('.danger-btn').forEach((btn) => {
    btn.addEventListener('click', () => { Store.removeWeapon(btn.dataset.id); renderWeaponList(); });
  });
}

