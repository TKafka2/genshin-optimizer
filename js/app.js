function renderWeaponOptResult() {
  const container = document.getElementById('wpn-opt-result');
  if (!container || !lastWeaponAssignmentResult) return;
  const { assignments, unassignedCharacters, leftoverWeapons } = lastWeaponAssignmentResult;
  const sorted = assignments.slice().sort((a, b) => b.score - a.score);
  container.innerHTML = `
    <h3>Recommended assignments</h3>
    ${sorted.length ? `<table class="data-table">
      <thead><tr><th>Character</th><th>Weapon</th><th>Refine</th><th>Score</th><th></th></tr></thead>
      <tbody>${sorted.map((a) => `
        <tr>
          <td>${avatarHtml(a.character, 'avatar-sm')} ${escapeHtml(a.character.name)}</td>
          <td>${weaponIconHtml(a.weapon)} ${escapeHtml(a.weapon.name)}${isPreferredWeapon(a.character.id, a.weapon.weaponId) ? ' <span class="pref-star" title="On the community best-weapons list for this character">★</span>' : ''}</td>
          <td>R${a.weapon.refinement}</td>
          <td>${a.score.toFixed(1)}</td>
          <td><button class="save-assign-btn" data-char="${a.character.id}" data-weapon="${a.weapon.instanceId}">Save</button></td>
        </tr>
      `).join('')}</tbody>
    </table>` : '<p class="hint">No matches yet — you need owned characters and weapons of the same type.</p>'}
    ${unassignedCharacters.length ? `<h3>Owned characters with no matching weapon in inventory</h3>
      <p>${unassignedCharacters.map((c) => escapeHtml(c.name)).join(', ')}</p>` : ''}
    ${leftoverWeapons.length ? `<h3>Unused weapons of matching types</h3>
      <p>${leftoverWeapons.map((w) => escapeHtml(w.name)).join(', ')}</p>` : ''}
  `;
  container.querySelectorAll('.save-assign-btn').forEach((btn) => {
    btn.addEventListener('click', () => {
      const weapon = Store.state.weapons.find((w) => w.instanceId === btn.dataset.weapon);
      if (weapon) {
        weapon.assignedTo = btn.dataset.char;
        Store.save();
        btn.textContent = 'Saved ✓';
        btn.disabled = true;
      }
    });
  });
}

